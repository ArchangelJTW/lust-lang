use crate::data::layout::CanonicalTypeTag;
use crate::mir::ir::*;
use alloc::{format, string::String, vec::Vec};

/// Options for C code generation from MIR.
#[derive(Debug, Clone)]
pub struct CEmitterOptions {
    pub is_library: bool,
    pub max_memory_bytes: Option<usize>,
}

impl Default for CEmitterOptions {
    fn default() -> Self {
        Self {
            is_library: false,
            max_memory_bytes: None,
        }
    }
}

/// Generates standard, portable C99 source code from a Lust MIR module.
pub fn emit_c_from_mir(module: &MirModule, opts: &CEmitterOptions) -> String {
    let mut out = String::new();

    // 1. Headers
    out.push_str("/* Generated by Lust AOT Compiler (Zig-Free Release Pipeline) */\n");
    out.push_str("#include <stdio.h>\n");
    out.push_str("#include <stdlib.h>\n");
    out.push_str("#include <stdint.h>\n");
    out.push_str("#include <stdbool.h>\n");
    out.push_str("#include <string.h>\n");
    out.push_str("#include <math.h>\n\n");

    // 2. Runtime Helpers & Memory Management
    emit_runtime_preamble(&mut out, opts);

    // 2.5. Struct Layouts & Decoders (Gate-SCHEMA-09/13 Lowering)
    emit_struct_layouts_and_decoders(&mut out, module);

    // 3. Forward declarations for all module functions
    out.push_str("/* Function Declarations */\n");
    for func in &module.functions {
        let ret_ty = mir_type_to_c(&func.signature.return_type);
        let fn_name = c_fn_name(&func.signature.name);
        out.push_str(&format!("{ret_ty} {fn_name}("));
        if func.params.is_empty() {
            out.push_str("void");
        } else {
            for (i, p_id) in func.params.iter().enumerate() {
                if i > 0 {
                    out.push_str(", ");
                }
                let param_ty = mir_type_to_c(&func.locals[p_id.0].ty);
                out.push_str(&format!("{param_ty} arg{i}"));
            }
        }
        out.push_str(");\n");
    }
    out.push('\n');

    // 4. Function definitions
    out.push_str("/* Function Definitions */\n");
    for func in &module.functions {
        emit_function(&mut out, func);
    }

    // 5. Main entrypoint (if not library)
    if !opts.is_library {
        out.push_str("/* Main Entrypoint */\n");
        out.push_str("int main(int argc, char** argv) {\n");
        out.push_str("    (void)argc;\n    (void)argv;\n");

        let main_fn = module
            .functions
            .iter()
            .find(|f| f.signature.name == "main" || f.signature.name.ends_with(".main"));
        if let Some(main) = main_fn {
            if main.signature.return_type == MirType::Unit {
                out.push_str("    __lust_fn_main();\n");
                out.push_str("    return 0;\n");
            } else {
                out.push_str("    int64_t res = (int64_t)__lust_fn_main();\n");
                out.push_str("    return (int)res;\n");
            }
        } else {
            out.push_str("    return 0;\n");
        }
        out.push_str("}\n");
    }

    out
}

fn emit_runtime_preamble(out: &mut String, opts: &CEmitterOptions) {
    out.push_str("/* Lust AOT Runtime Helpers */\n");

    if let Some(limit) = opts.max_memory_bytes {
        out.push_str(&format!(
            "static size_t __lust_max_mem = {limit}ULL;\n\
             static size_t __lust_used_mem = 0;\n\
             static void* __lust_alloc(size_t sz) {{\n\
                 if (__lust_used_mem + sz > __lust_max_mem) {{\n\
                     fprintf(stderr, \"runtime error: memory limit exceeded\\n\");\n\
                     exit(1);\n\
                 }}\n\
                 void* p = malloc(sz);\n\
                 if (!p) {{ fprintf(stderr, \"out of memory\\n\"); exit(1); }}\n\
                 __lust_used_mem += sz;\n\
                 return p;\n\
             }}\n\n"
        ));
    } else {
        out.push_str(
            "static inline void* __lust_alloc(size_t sz) {\n\
                 void* p = malloc(sz);\n\
                 if (!p) { fprintf(stderr, \"out of memory\\n\"); exit(1); }\n\
                 return p;\n\
             }\n\n",
        );
    }

    out.push_str(
        "/* Arithmetic with division-by-zero checks */\n\
         static inline int64_t __lust_div_int(int64_t a, int64_t b) {\n\
             if (b == 0) { fprintf(stderr, \"runtime error: division by zero\\n\"); exit(1); }\n\
             return a / b;\n\
         }\n\
         static inline int64_t __lust_rem_int(int64_t a, int64_t b) {\n\
             if (b == 0) { fprintf(stderr, \"runtime error: division by zero\\n\"); exit(1); }\n\
             return a % b;\n\
         }\n\
         static inline int64_t __lust_floordiv_int(int64_t a, int64_t b) {\n\
             if (b == 0) { fprintf(stderr, \"runtime error: division by zero\\n\"); exit(1); }\n\
             int64_t q = a / b;\n\
             int64_t r = a % b;\n\
             if ((r != 0) && ((a < 0) ^ (b < 0))) q -= 1;\n\
             return q;\n\
         }\n\
         static inline int64_t __lust_pow_int(int64_t base, int64_t exp) {\n\
             if (exp < 0) return 0;\n\
             int64_t res = 1;\n\
             int64_t b = base;\n\
             while (exp > 0) {\n\
                 if (exp & 1) res *= b;\n\
                 b *= b;\n\
                 exp >>= 1;\n\
             }\n\
             return res;\n\
         }\n\
         static inline int64_t __lust_abs_int(int64_t a) { return a < 0 ? -a : a; }\n\
         static inline int64_t __lust_min_int(int64_t a, int64_t b) { return a < b ? a : b; }\n\
         static inline int64_t __lust_max_int(int64_t a, int64_t b) { return a > b ? a : b; }\n\
         static inline int64_t __lust_clamp_int(int64_t v, int64_t min, int64_t max) {\n\
             if (v < min) return min;\n\
             if (v > max) return max;\n\
             return v;\n\
         }\n\
         static inline double __lust_floordiv_float(double a, double b) {\n\
             if (b == 0.0) { fprintf(stderr, \"runtime error: division by zero\\n\"); exit(1); }\n\
             return floor(a / b);\n\
         }\n\n",
    );

    out.push_str(
        "/* Output Helpers */\n\
         static inline void __lust_print_int(int64_t v) { printf(\"%lld\", (long long)v); }\n\
         static inline void __lust_println_int(int64_t v) { printf(\"%lld\\n\", (long long)v); }\n\
         static inline void __lust_print_float(double v) { printf(\"%g\", v); }\n\
         static inline void __lust_println_float(double v) { printf(\"%g\\n\", v); }\n\
         static inline void __lust_print_str(const char* s) { if (s) fputs(s, stdout); }\n\
         static inline void __lust_println_str(const char* s) { if (s) puts(s); else puts(\"\"); }\n\
         static inline void __lust_print_bool(bool b) { fputs(b ? \"true\" : \"false\", stdout); }\n\
         static inline void __lust_println_bool(bool b) { puts(b ? \"true\" : \"false\"); }\n\n",
    );

    out.push_str(
        "/* Dynamic Array Implementation */\n\
         typedef struct {\n\
             int64_t* data;\n\
             size_t len;\n\
             size_t cap;\n\
         } LustArray;\n\
         static inline LustArray* __lust_alloc_array(size_t cap) {\n\
             LustArray* a = (LustArray*)__lust_alloc(sizeof(LustArray));\n\
             size_t actual_cap = cap < 4 ? 4 : cap;\n\
             a->data = (int64_t*)__lust_alloc(sizeof(int64_t) * actual_cap);\n\
             a->len = 0;\n\
             a->cap = actual_cap;\n\
             return a;\n\
         }\n\
         static inline void __lust_array_push(LustArray* a, int64_t val) {\n\
             if (a->len >= a->cap) {\n\
                 a->cap = a->cap < 4 ? 4 : a->cap * 2;\n\
                 a->data = (int64_t*)realloc(a->data, sizeof(int64_t) * a->cap);\n\
                 if (!a->data) { fprintf(stderr, \"out of memory\\n\"); exit(1); }\n\
             }\n\
             a->data[a->len++] = val;\n\
         }\n\
         static inline int64_t __lust_array_get(LustArray* a, int64_t idx) {\n\
             if (idx < 0 || (size_t)idx >= a->len) {\n\
                 fprintf(stderr, \"runtime error: index out of bounds\\n\");\n\
                 exit(1);\n\
             }\n\
             return a->data[idx];\n\
         }\n\
         static inline void __lust_array_set(LustArray* a, int64_t idx, int64_t val) {\n\
             if (idx < 0 || (size_t)idx >= a->len) {\n\
                 fprintf(stderr, \"runtime error: index out of bounds\\n\");\n\
                 exit(1);\n\
             }\n\
             a->data[idx] = val;\n\
         }\n\
         static inline int64_t __lust_array_len(LustArray* a) { return (int64_t)a->len; }\n\n",
    );

    out.push_str(
        "/* String Concat */\n\
         static inline const char* __lust_string_concat(const char* a, const char* b) {\n\
             if (!a) a = \"\";\n\
             if (!b) b = \"\";\n\
             size_t la = strlen(a);\n\
             size_t lb = strlen(b);\n\
             char* buf = (char*)__lust_alloc(la + lb + 1);\n\
             memcpy(buf, a, la);\n\
             memcpy(buf + la, b, lb);\n\
             buf[la + lb] = '\\0';\n\
             return buf;\n\
         }\n\n",
    );
}

fn emit_struct_layouts_and_decoders(out: &mut String, module: &MirModule) {
    if module.struct_layouts.is_empty() {
        return;
    }

    out.push_str("/* Struct Layouts & Decoders (Gate-SCHEMA-09/13 Lowering) */\n");

    for layout in &module.struct_layouts {
        let type_name = &layout.type_name;
        out.push_str(&format!(
            "/* Layout: {} (size={}, align={}, c_flat={}) */\n",
            type_name, layout.size_bytes, layout.align_bytes, layout.is_c_flat
        ));
        out.push_str(&format!("typedef struct LustStruct_{type_name} {{\n"));
        for f in &layout.fields {
            let c_ty = match f.tag {
                CanonicalTypeTag::Bool => "bool",
                CanonicalTypeTag::Int64
                | CanonicalTypeTag::UInt64
                | CanonicalTypeTag::DateTimeUtc => "int64_t",
                CanonicalTypeTag::Float64 => "double",
                CanonicalTypeTag::StringSlice | CanonicalTypeTag::BinarySlice => "const char*",
                _ => "int64_t",
            };
            out.push_str(&format!(
                "    {c_ty} field_{}; /* {} (offset={}, size={}) */\n",
                f.ordinal, f.name, f.byte_offset, f.byte_size
            ));
        }
        out.push_str(&format!("}} LustStruct_{type_name};\n\n"));

        let mut required_mask: u64 = 0;
        for f in &layout.fields {
            if !f.is_optional {
                required_mask |= 1u64 << f.ordinal;
            }
        }

        out.push_str(&format!(
            "static LustStruct_{type_name} __mir_struct_decode_into_{type_name}(const char* json_input) {{\n\
             if (!json_input) {{\n\
                 fprintf(stderr, \"runtime error: null JSON input for struct {type_name}\\n\");\n\
                 exit(1);\n\
             }}\n\
             const char* s = json_input;\n\
             while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n\
             if (*s != '{{') {{\n\
                 fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: expected '{{' at offset %ld\\n\", (long)(s - json_input));\n\
                 exit(1);\n\
             }}\n\
             s++;\n\
             LustStruct_{type_name} out;\n\
             memset(&out, 0, sizeof(out));\n\
             uint64_t initialized_mask = 0;\n\
             void* allocated_ptrs[64];\n\
             int alloc_count = 0;\n\
             memset(allocated_ptrs, 0, sizeof(allocated_ptrs));\n\
             while (1) {{\n\
                 while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n\
                 if (*s == '}}') {{\n\
                     s++;\n\
                     break;\n\
                 }}\n\
                 if (*s != '\"') {{\n\
                     for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                     fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: expected string key\\n\");\n\
                     exit(1);\n\
                 }}\n\
                 s++;\n\
                 const char* key_start = s;\n\
                 while (*s && *s != '\"') {{\n\
                     if (*s == '\\\\' && *(s + 1)) s += 2;\n\
                     else s++;\n\
                 }}\n\
                 if (*s != '\"') {{\n\
                     for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                     fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: unterminated key\\n\");\n\
                     exit(1);\n\
                 }}\n\
                 size_t key_len = (size_t)(s - key_start);\n\
                 s++;\n\
                 while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n\
                 if (*s != ':') {{\n\
                     for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                     fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: expected ':'\\n\");\n\
                     exit(1);\n\
                 }}\n\
                 s++;\n\
                 while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n"
        ));

        for (i, f) in layout.fields.iter().enumerate() {
            let else_if = if i == 0 { "if" } else { "else if" };
            let f_name = &f.name;
            let f_ord = f.ordinal;
            out.push_str(&format!(
                "                {else_if} (key_len == {} && strncmp(key_start, \"{f_name}\", key_len) == 0) {{\n\
                 if (initialized_mask & (1ULL << {f_ord})) {{\n\
                     for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                     fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: duplicate key '{f_name}'\\n\");\n\
                     exit(1);\n\
                 }}\n",
                f_name.len()
            ));

            match f.tag {
                CanonicalTypeTag::Int64
                | CanonicalTypeTag::UInt64
                | CanonicalTypeTag::DateTimeUtc => {
                    out.push_str(&format!(
                        "                    char* endptr = NULL;\n\
                         long long v = strtoll(s, &endptr, 10);\n\
                         if (endptr == s) {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: invalid integer for {f_name}\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         s = endptr;\n\
                         out.field_{f_ord} = (int64_t)v;\n\
                         initialized_mask |= (1ULL << {f_ord});\n"
                    ));
                }
                CanonicalTypeTag::Float64 => {
                    out.push_str(&format!(
                        "                    char* endptr = NULL;\n\
                         double v = strtod(s, &endptr);\n\
                         if (endptr == s) {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: invalid float for {f_name}\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         s = endptr;\n\
                         out.field_{f_ord} = v;\n\
                         initialized_mask |= (1ULL << {f_ord});\n"
                    ));
                }
                CanonicalTypeTag::Bool => {
                    out.push_str(&format!(
                        "                    if (strncmp(s, \"true\", 4) == 0) {{\n\
                             out.field_{f_ord} = true;\n\
                             s += 4;\n\
                         }} else if (strncmp(s, \"false\", 5) == 0) {{\n\
                             out.field_{f_ord} = false;\n\
                             s += 5;\n\
                         }} else {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: invalid bool for {f_name}\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         initialized_mask |= (1ULL << {f_ord});\n"
                    ));
                }
                CanonicalTypeTag::StringSlice | CanonicalTypeTag::BinarySlice => {
                    out.push_str(&format!(
                        "                    if (*s != '\"') {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: expected string for {f_name}\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         s++;\n\
                         const char* v_start = s;\n\
                         while (*s && *s != '\"') {{\n\
                             if (*s == '\\\\' && *(s + 1)) s += 2;\n\
                             else s++;\n\
                         }}\n\
                         if (*s != '\"') {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: unterminated string for {f_name}\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         size_t v_len = (size_t)(s - v_start);\n\
                         s++;\n\
                         char* str_copy = (char*)malloc(v_len + 1);\n\
                         if (!str_copy) {{\n\
                             for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                             fprintf(stderr, \"out of memory\\n\");\n\
                             exit(1);\n\
                         }}\n\
                         memcpy(str_copy, v_start, v_len);\n\
                         str_copy[v_len] = '\\0';\n\
                         allocated_ptrs[alloc_count++] = str_copy;\n\
                         out.field_{f_ord} = str_copy;\n\
                         initialized_mask |= (1ULL << {f_ord});\n"
                    ));
                }
                _ => {
                    out.push_str(&format!(
                        "                    out.field_{f_ord} = 0;\n\
                         initialized_mask |= (1ULL << {f_ord});\n"
                    ));
                }
            }
            out.push_str("                }\n");
        }

        out.push_str(
            "                else {\n\
                 if (*s == '\"') {\n\
                     s++;\n\
                     while (*s && *s != '\"') {\n\
                         if (*s == '\\\\' && *(s + 1)) s += 2;\n\
                         else s++;\n\
                     }\n\
                     if (*s == '\"') s++;\n\
                 } else if (*s == '{') {\n\
                     int depth = 1;\n\
                     s++;\n\
                     while (*s && depth > 0) {\n\
                         if (*s == '{') depth++;\n\
                         else if (*s == '}') depth--;\n\
                         s++;\n\
                     }\n\
                 } else if (*s == '[') {\n\
                     int depth = 1;\n\
                     s++;\n\
                     while (*s && depth > 0) {\n\
                         if (*s == '[') depth++;\n\
                         else if (*s == ']') depth--;\n\
                         s++;\n\
                     }\n\
                 } else {\n\
                     while (*s && *s != ',' && *s != '}' && *s != ' ' && *s != '\\t' && *s != '\\r' && *s != '\\n') s++;\n\
                 }\n\
             }\n\
             while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n\
             if (*s == ',') {\n\
                 s++;\n\
                 continue;\n\
             } else if (*s == '}') {\n\
                 s++;\n\
                 break;\n\
             } else {\n\
                 for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                 fprintf(stderr, \"runtime error: JSON decode error: expected ',' or '}'\\n\");\n\
                 exit(1);\n\
             }\n\
         }\n"
        );

        out.push_str(&format!(
            "    uint64_t required_mask = {required_mask}ULL;\n\
             if ((initialized_mask & required_mask) != required_mask) {{\n\
                 for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                 fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: missing required fields\\n\");\n\
                 exit(1);\n\
             }}\n\
             while (*s == ' ' || *s == '\\t' || *s == '\\r' || *s == '\\n') s++;\n\
             if (*s != '\\0') {{\n\
                 for (int k = 0; k < alloc_count; k++) if (allocated_ptrs[k]) free(allocated_ptrs[k]);\n\
                 fprintf(stderr, \"runtime error: JSON decode error for struct {type_name}: trailing junk after object\\n\");\n\
                 exit(1);\n\
             }}\n\
             return out;\n\
         }}\n\n"
        ));

        out.push_str(&format!(
            "__attribute__((noinline)) static LustStruct_{type_name} __mir_struct_decode_binary_{type_name}(const uint8_t* raw, size_t len) {{\n\
             if (!raw || len < {size_bytes}ULL) {{\n\
                 fprintf(stderr, \"SchemaDecodeError::TruncatedPayload {{ expected: {size_bytes}, actual: %zu }}\\n\", len);\n\
                 exit(1);\n\
             }}\n\
             LustStruct_{type_name} out;\n\
             memset(&out, 0, sizeof(out));\n",
            size_bytes = layout.size_bytes
        ));
        for f in &layout.fields {
            let f_ord = f.ordinal;
            let f_off = f.byte_offset;
            match f.tag {
                CanonicalTypeTag::Bool => {
                    out.push_str(&format!(
                        "             out.field_{f_ord} = (raw[{f_off}] != 0);\n"
                    ));
                }
                CanonicalTypeTag::Int64
                | CanonicalTypeTag::UInt64
                | CanonicalTypeTag::DateTimeUtc => {
                    out.push_str(&format!(
                        "             memcpy(&out.field_{f_ord}, raw + {f_off}, sizeof(int64_t));\n"
                    ));
                }
                CanonicalTypeTag::Float64 => {
                    out.push_str(&format!(
                        "             memcpy(&out.field_{f_ord}, raw + {f_off}, sizeof(double));\n"
                    ));
                }
                _ => {
                    out.push_str(&format!(
                        "             memcpy(&out.field_{f_ord}, raw + {f_off}, sizeof(int64_t));\n"
                    ));
                }
            }
        }
        out.push_str("             return out;\n         }\n\n");
    }
}

fn emit_function(out: &mut String, func: &MirFunction) {
    let ret_ty = mir_type_to_c(&func.signature.return_type);
    let fn_name = c_fn_name(&func.signature.name);

    out.push_str(&format!("{ret_ty} {fn_name}("));
    if func.params.is_empty() {
        out.push_str("void");
    } else {
        for (i, p_id) in func.params.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            let param_ty = mir_type_to_c(&func.locals[p_id.0].ty);
            out.push_str(&format!("{param_ty} arg{i}"));
        }
    }
    out.push_str(") {\n");

    // Declare locals
    for local in &func.locals {
        let ty = mir_local_type_to_c(&local.ty);
        let default_val = default_c_value(&local.ty);
        out.push_str(&format!("    {ty} _{} = {default_val};\n", local.id.0));
    }

    // Initialize params
    for (i, p_id) in func.params.iter().enumerate() {
        out.push_str(&format!("    _{} = arg{i};\n", p_id.0));
    }

    out.push_str(&format!("    goto bb{};\n\n", func.entry.0));

    // Emit basic blocks
    for (idx, block) in func.blocks.iter().enumerate() {
        out.push_str(&format!("bb{idx}: ;\n"));
        for stmt in &block.statements {
            emit_statement(out, stmt);
        }

        if let Some(term) = &block.terminator {
            emit_terminator(out, term, &func.signature.return_type, func);
        } else {
            out.push_str("    abort();\n");
        }
        out.push('\n');
    }

    out.push_str("}\n\n");
}

fn emit_statement(out: &mut String, stmt: &Statement) {
    match stmt {
        Statement::Assign(place, rval, _) => {
            match place {
                Place::Index(base, idx) => {
                    let b_expr = place_to_c(base);
                    let val_expr = rvalue_to_c(rval);
                    out.push_str(&format!(
                        "    __lust_array_set({b_expr}, _{}, {val_expr});\n",
                        idx.0
                    ));
                }
                _ => {
                    let p_expr = place_to_c(place);
                    let r_expr = rvalue_to_c(rval);
                    out.push_str(&format!("    {p_expr} = {r_expr};\n"));
                }
            }
        }
        Statement::StorageLive(_, _) | Statement::StorageDead(_, _) => {}
        Statement::ResourceCheck(_, _, _) => {}
    }
}

fn emit_terminator(
    out: &mut String,
    term: &Terminator,
    ret_ty: &MirType,
    func: &MirFunction,
) {
    match term {
        Terminator::Goto(target, _) => {
            out.push_str(&format!("    goto bb{};\n", target.0));
        }
        Terminator::Cond {
            cond,
            then_block,
            else_block,
            ..
        } => {
            let c_expr = operand_to_c(cond);
            out.push_str(&format!(
                "    if ({c_expr}) goto bb{}; else goto bb{};\n",
                then_block.0, else_block.0
            ));
        }
        Terminator::Switch {
            discr,
            cases,
            default,
            ..
        } => {
            let d_expr = operand_to_c(discr);
            out.push_str(&format!("    switch ({d_expr}) {{\n"));
            for (val, target) in cases {
                out.push_str(&format!("        case {val}: goto bb{};\n", target.0));
            }
            out.push_str(&format!("        default: goto bb{};\n    }}\n", default.0));
        }
        Terminator::Call {
            callee,
            args,
            destination,
            success,
            error: _,
            ..
        } => {
            let dest_expr = place_to_c(destination);

            if let Some(struct_name) = parse_mir_struct_decode_callee(callee) {
                let arg_expr = args.first().map(operand_to_c).unwrap_or_else(|| "\"\"".into());
                out.push_str(&format!(
                    "    {dest_expr} = __mir_struct_decode_into_{struct_name}({arg_expr});\n"
                ));
                out.push_str(&format!("    goto bb{};\n", success.0));
                return;
            }
            if let Some(struct_name) = callee.strip_prefix("__lust_mir_struct_decode_binary:") {
                let ptr_expr = args.first().map(operand_to_c).unwrap_or_else(|| "NULL".into());
                let len_expr = args.get(1).map(operand_to_c).unwrap_or_else(|| "0".into());
                out.push_str(&format!(
                    "    {dest_expr} = __mir_struct_decode_binary_{struct_name}((const uint8_t*)(uintptr_t)({ptr_expr}), (size_t)({len_expr}));\n"
                ));
                out.push_str(&format!("    goto bb{};\n", success.0));
                return;
            }

            match callee.as_str() {
                "print" | "println" => {
                    let is_ln = callee == "println";
                    if let Some(arg) = args.first() {
                        let arg_expr = operand_to_c(arg);
                        let arg_ty = infer_operand_type(arg, func);
                        match arg_ty {
                            MirType::Float => {
                                if is_ln {
                                    out.push_str(&format!("    __lust_println_float({arg_expr});\n"));
                                } else {
                                    out.push_str(&format!("    __lust_print_float({arg_expr});\n"));
                                }
                            }
                            MirType::String => {
                                if is_ln {
                                    out.push_str(&format!("    __lust_println_str({arg_expr});\n"));
                                } else {
                                    out.push_str(&format!("    __lust_print_str({arg_expr});\n"));
                                }
                            }
                            MirType::Bool => {
                                if is_ln {
                                    out.push_str(&format!("    __lust_println_bool({arg_expr});\n"));
                                } else {
                                    out.push_str(&format!("    __lust_print_bool({arg_expr});\n"));
                                }
                            }
                            _ => {
                                if is_ln {
                                    out.push_str(&format!("    __lust_println_int({arg_expr});\n"));
                                } else {
                                    out.push_str(&format!("    __lust_print_int({arg_expr});\n"));
                                }
                            }
                        }
                    } else if is_ln {
                        out.push_str("    puts(\"\");\n");
                    }
                }
                "abs" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0".into());
                    out.push_str(&format!("    {dest_expr} = __lust_abs_int({a});\n"));
                }
                "min" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0".into());
                    let b = args.get(1).map(operand_to_c).unwrap_or_else(|| "0".into());
                    out.push_str(&format!("    {dest_expr} = __lust_min_int({a}, {b});\n"));
                }
                "max" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0".into());
                    let b = args.get(1).map(operand_to_c).unwrap_or_else(|| "0".into());
                    out.push_str(&format!("    {dest_expr} = __lust_max_int({a}, {b});\n"));
                }
                "clamp" => {
                    let v = args.first().map(operand_to_c).unwrap_or_else(|| "0".into());
                    let min = args.get(1).map(operand_to_c).unwrap_or_else(|| "0".into());
                    let max = args.get(2).map(operand_to_c).unwrap_or_else(|| "0".into());
                    out.push_str(&format!("    {dest_expr} = __lust_clamp_int({v}, {min}, {max});\n"));
                }
                "floor" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0.0".into());
                    out.push_str(&format!("    {dest_expr} = floor({a});\n"));
                }
                "ceil" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0.0".into());
                    out.push_str(&format!("    {dest_expr} = ceil({a});\n"));
                }
                "sqrt" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0.0".into());
                    out.push_str(&format!("    {dest_expr} = sqrt({a});\n"));
                }
                "round" => {
                    let a = args.first().map(operand_to_c).unwrap_or_else(|| "0.0".into());
                    out.push_str(&format!("    {dest_expr} = round({a});\n"));
                }
                other => {
                    let c_callee = c_fn_name(other);
                    let arg_exprs: Vec<String> = args.iter().map(operand_to_c).collect();
                    let dest_is_unit = match destination {
                        Place::Local(id) => func.locals.get(id.0).map(|d| d.ty == MirType::Unit).unwrap_or(false),
                        _ => false,
                    };
                    if dest_is_unit {
                        out.push_str(&format!("    {c_callee}({});\n", arg_exprs.join(", ")));
                    } else {
                        out.push_str(&format!("    {dest_expr} = {c_callee}({});\n", arg_exprs.join(", ")));
                    }
                }
            }

            out.push_str(&format!("    goto bb{};\n", success.0));
        }
        Terminator::Return(opt_val, _) => {
            if let Some(val) = opt_val {
                let v_expr = operand_to_c(val);
                out.push_str(&format!("    return {v_expr};\n"));
            } else if *ret_ty == MirType::Unit {
                out.push_str("    return;\n");
            } else {
                out.push_str("    return 0;\n");
            }
        }
        Terminator::Raise(err_op, _) => {
            let e_expr = operand_to_c(err_op);
            out.push_str(&format!(
                "    fprintf(stderr, \"runtime error: %lld\\n\", (long long){e_expr});\n    exit(1);\n"
            ));
        }
        Terminator::Unreachable(_) => {
            out.push_str("    abort();\n");
        }
    }
}

fn place_to_c(place: &Place) -> String {
    match place {
        Place::Local(id) => format!("_{}", id.0),
        Place::Field(base, idx) => format!("{}.field_{}", place_to_c(base), idx),
        Place::Index(base, idx) => format!("__lust_array_get({}, _{})", place_to_c(base), idx.0),
    }
}

fn operand_to_c(op: &Operand) -> String {
    match op {
        Operand::Copy(p) | Operand::Move(p) => place_to_c(p),
        Operand::Constant(c) => constant_to_c(c),
    }
}

fn constant_to_c(c: &MirConstant) -> String {
    match c {
        MirConstant::Unit => "0".into(),
        MirConstant::Bool(b) => if *b { "true".into() } else { "false".into() },
        MirConstant::Int(i) => format!("{i}LL"),
        MirConstant::Float(f) => {
            let s = format!("{f}");
            if s.contains('.') { s } else { format!("{s}.0") }
        }
        MirConstant::String(s) => {
            format!("\"{}\"", s.replace('\\', "\\\\").replace('\"', "\\\"").replace('\n', "\\n"))
        }
    }
}

fn rvalue_to_c(rval: &Rvalue) -> String {
    match rval {
        Rvalue::Use(op) => operand_to_c(op),
        Rvalue::BinaryOp(binop, l, r) => {
            let l_expr = operand_to_c(l);
            let r_expr = operand_to_c(r);
            match binop {
                MirBinaryOp::Add => format!("({l_expr} + {r_expr})"),
                MirBinaryOp::Sub => format!("({l_expr} - {r_expr})"),
                MirBinaryOp::Mul => format!("({l_expr} * {r_expr})"),
                MirBinaryOp::Div => format!("__lust_div_int({l_expr}, {r_expr})"),
                MirBinaryOp::Mod => format!("__lust_rem_int({l_expr}, {r_expr})"),
                MirBinaryOp::FloorDiv => format!("__lust_floordiv_int({l_expr}, {r_expr})"),
                MirBinaryOp::Pow => format!("__lust_pow_int({l_expr}, {r_expr})"),
                MirBinaryOp::BitAnd => format!("({l_expr} & {r_expr})"),
                MirBinaryOp::BitOr => format!("({l_expr} | {r_expr})"),
                MirBinaryOp::BitXor => format!("({l_expr} ^ {r_expr})"),
                MirBinaryOp::Shl => format!("({l_expr} << {r_expr})"),
                MirBinaryOp::Shr => format!("({l_expr} >> {r_expr})"),
                MirBinaryOp::Eq => format!("({l_expr} == {r_expr})"),
                MirBinaryOp::NotEq => format!("({l_expr} != {r_expr})"),
                MirBinaryOp::Lt => format!("({l_expr} < {r_expr})"),
                MirBinaryOp::LtEq => format!("({l_expr} <= {r_expr})"),
                MirBinaryOp::Gt => format!("({l_expr} > {r_expr})"),
                MirBinaryOp::GtEq => format!("({l_expr} >= {r_expr})"),
                MirBinaryOp::And => format!("({l_expr} && {r_expr})"),
                MirBinaryOp::Or => format!("({l_expr} || {r_expr})"),
                MirBinaryOp::Concat => format!("__lust_str_concat({l_expr}, {r_expr})"),
            }
        }
        Rvalue::UnaryOp(unop, op) => {
            let o_expr = operand_to_c(op);
            match unop {
                MirUnaryOp::Neg => format!("(-{o_expr})"),
                MirUnaryOp::Not => format!("(!{o_expr})"),
                MirUnaryOp::BitNot => format!("(~{o_expr})"),
                MirUnaryOp::Len => format!("__lust_array_len({o_expr})"),
            }
        }
        Rvalue::Cast(op, target_ty) => {
            let o_expr = operand_to_c(op);
            let c_ty = mir_type_to_c(target_ty);
            format!("(({c_ty}){o_expr})")
        }
        Rvalue::Aggregate(ty, operands) => {
            match ty {
                MirType::Array(_) => {
                    let mut s = format!("__lust_alloc_array({})", operands.len());
                    // If items need pushing, emit comma operator or builder
                    if !operands.is_empty() {
                        let pushes: Vec<String> = operands
                            .iter()
                            .map(|op| format!("__lust_array_push(__arr_tmp, {})", operand_to_c(op)))
                            .collect();
                        s = format!("({{ LustArray* __arr_tmp = {s}; {}; __arr_tmp; }})", pushes.join("; "));
                    }
                    s
                }
                _ => "0".into(),
            }
        }
        Rvalue::Closure { .. } => "0 /* closure unsupported in C99 emitter */".to_string(),
    }
}

fn mir_local_type_to_c(ty: &MirType) -> String {
    match ty {
        MirType::Unit => "uint8_t".into(),
        _ => mir_type_to_c(ty),
    }
}

fn mir_type_to_c(ty: &MirType) -> String {
    match ty {
        MirType::Unit => "void".into(),
        MirType::Bool => "bool".into(),
        MirType::Int => "int64_t".into(),
        MirType::Float => "double".into(),
        MirType::String => "const char*".into(),
        MirType::Array(_) => "LustArray*".into(),
        MirType::Struct(name) => format!("LustStruct_{name}"),
        _ => "int64_t".into(),
    }
}

fn default_c_value(ty: &MirType) -> &'static str {
    match ty {
        MirType::Unit => "0",
        MirType::Bool => "false",
        MirType::Int => "0",
        MirType::Float => "0.0",
        MirType::String => "\"\"",
        MirType::Array(_) => "NULL",
        MirType::Struct(_) => "{0}",
        _ => "0",
    }
}

fn c_fn_name(name: &str) -> String {
    if name == "main" || name.ends_with(".main") {
        "__lust_fn_main".into()
    } else {
        let safe = name.replace('.', "_").replace('-', "_");
        format!("__lust_user_{safe}")
    }
}

fn infer_operand_type(op: &Operand, func: &MirFunction) -> MirType {
    match op {
        Operand::Constant(c) => match c {
            MirConstant::Unit => MirType::Unit,
            MirConstant::Bool(_) => MirType::Bool,
            MirConstant::Int(_) => MirType::Int,
            MirConstant::Float(_) => MirType::Float,
            MirConstant::String(_) => MirType::String,
        },
        Operand::Copy(Place::Local(id)) | Operand::Move(Place::Local(id)) => {
            func.locals.get(id.0).map(|d| d.ty.clone()).unwrap_or(MirType::Int)
        }
        _ => MirType::Int,
    }
}
