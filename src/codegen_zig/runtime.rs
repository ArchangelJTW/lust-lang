const ARRAY_RUNTIME_SRC: &str = r#"pub fn LustArray(comptime T: type) type {
    return struct {
        items: []T,
        capacity: usize,
        allocator: std.mem.Allocator,

        pub fn init(allocator: std.mem.Allocator) @This() {
            return .{
                .items = &[_]T{},
                .capacity = 0,
                .allocator = allocator,
            };
        }

        pub fn fromSlice(allocator: std.mem.Allocator, slice_items: []const T) !@This() {
            var res = @This().init(allocator);
            for (slice_items) |item| {
                try res.push(item);
            }
            return res;
        }

        pub fn push(self: *@This(), item: T) !void {
            if (self.items.len >= self.capacity) {
                const new_cap = if (self.capacity == 0) 8 else self.capacity * 2;
                const new_items = try self.allocator.alloc(T, new_cap);
                if (self.items.len > 0) {
                    @memcpy(new_items[0..self.items.len], self.items);
                }
                self.items.ptr = new_items.ptr;
                self.capacity = new_cap;
            }
            const old_len = self.items.len;
            self.items.len = old_len + 1;
            self.items[old_len] = item;
        }

        pub fn pop(self: *@This()) ?T {
            if (self.items.len == 0) return null;
            self.items.len -= 1;
            return self.items[self.items.len];
        }

        pub fn clear(self: *@This()) void {
            self.items.len = 0;
        }

        pub inline fn get(self: *const @This(), idx: i64) ?T {
            if (idx < 0 or @as(usize, @intCast(idx)) >= self.items.len) return null;
            return self.items[@as(usize, @intCast(idx))];
        }

        pub inline fn get_direct(self: *const @This(), idx: i64) T {
            if (idx < 0 or @as(usize, @intCast(idx)) >= self.items.len) {
                @panic("Array index out of bounds");
            }
            return self.items[@as(usize, @intCast(idx))];
        }

        pub inline fn set(self: *@This(), idx: i64, val: T) void {
            self.items[@as(usize, @intCast(idx))] = val;
        }

        pub inline fn len(self: *const @This()) i64 {
            return @as(i64, @intCast(self.items.len));
        }

        pub fn is_empty(self: *const @This()) bool {
            return self.items.len == 0;
        }

        pub fn first(self: *const @This()) ?T {
            return self.get(0);
        }

        pub fn last(self: *const @This()) ?T {
            if (self.items.len == 0) return null;
            return self.items[self.items.len - 1];
        }

        pub fn contains(self: *const @This(), val: T) bool {
            for (self.items) |item| {
                if (item == val) return true;
            }
            return false;
        }

        pub fn reverse(self: *@This()) void {
            std.mem.reverse(T, self.items);
        }

        pub fn insert(self: *@This(), idx: i64, item: T) !void {
            if (idx < 0) return;
            var u_idx = @as(usize, @intCast(idx));
            if (u_idx > self.items.len) u_idx = self.items.len;
            try self.push(item);
            if (u_idx < self.items.len - 1) {
                const end = self.items.len - 1;
                var i = end;
                while (i > u_idx) : (i -= 1) {
                    self.items[i] = self.items[i - 1];
                }
                self.items[u_idx] = item;
            }
        }

        pub fn remove(self: *@This(), idx: i64) ?T {
            if (idx < 0 or @as(usize, @intCast(idx)) >= self.items.len) return null;
            const u_idx = @as(usize, @intCast(idx));
            const removed = self.items[u_idx];
            var i = u_idx;
            while (i + 1 < self.items.len) : (i += 1) {
                self.items[i] = self.items[i + 1];
            }
            self.items.len -= 1;
            return removed;
        }

        fn lessThan(_: void, a: T, b: T) bool {
            return a < b;
        }

        pub fn sort(self: *@This()) void {
            if (self.items.len <= 1) return;
            std.mem.sort(T, self.items, {}, lessThan);
        }

        pub fn slice(self: *const @This(), start: i64, end: i64) !@This() {
            var res = @This().init(self.allocator);
            const len_i64: i64 = @as(i64, @intCast(self.items.len));
            var s = start;
            if (s < 0) s = 0;
            if (s > len_i64) s = len_i64;
            var e = end;
            if (e < 0) e = 0;
            if (e > len_i64) e = len_i64;
            if (s > e) return res;
            const us: usize = @as(usize, @intCast(s));
            const ue: usize = @as(usize, @intCast(e));
            for (self.items[us..ue]) |item| {
                try res.push(item);
            }
            return res;
        }
    };
}
"#;

